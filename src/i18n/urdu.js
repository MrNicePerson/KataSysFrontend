const translatedAttributes = ['placeholder', 'title', 'aria-label']
const textRecords = new WeakMap()
const attributeRecords = new WeakMap()

function preserveWhitespace(source, translated) {
  const leading = source.match(/^\s*/)?.[0] || ''
  const trailing = source.match(/\s*$/)?.[0] || ''
  return `${leading}${translated}${trailing}`
}

function translationFor(english) {
  const direct = urduMessages[english] ?? additionalUrduMessages[english]
  if (direct) return direct
  let match = english.match(/^Draft · (.+)$/)
  if (match) return `ڈرافٹ · ${match[1]}`
  match = english.match(/^Bank movement · (.+)$/)
  if (match) return `بینک کی نقل و حرکت · ${match[1]}`
  match = english.match(/^Rs\.\s*(.+)$/)
  if (match) return `روپے ${match[1]}`
  match = english.match(/^No bills match "(.*)"\.$/)
  if (match) return `اس تلاش سے کوئی بل نہیں ملا: "${match[1]}"`
  return null
}

function applyTextLanguage(node, language) {
  const current = node.nodeValue || ''
  const trimmed = current.trim()
  const record = textRecords.get(node)

  if (language === 'en') {
    if (record && trimmed === record.urdu) node.nodeValue = preserveWhitespace(current, record.english)
    return
  }

  if (record && trimmed === record.urdu) return
  const english = trimmed
  const urdu = translationFor(english)
  if (!urdu) return
  textRecords.set(node, { english, urdu })
  node.nodeValue = preserveWhitespace(current, urdu)
}

function applyAttributeLanguage(element, attribute, language) {
  const current = element.getAttribute(attribute)
  if (!current) return
  let records = attributeRecords.get(element)
  if (!records) {
    records = new Map()
    attributeRecords.set(element, records)
  }
  const record = records.get(attribute)

  if (language === 'en') {
    if (record && current === record.urdu) element.setAttribute(attribute, record.english)
    return
  }

  if (record && current === record.urdu) return
  const urdu = translationFor(current)
  if (!urdu) return
  records.set(attribute, { english: current, urdu })
  element.setAttribute(attribute, urdu)
}

function translateTree(root, language) {
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT)
  let node = walker.nextNode()
  while (node) {
    if (!node.parentElement?.closest('script,style,svg,[data-no-translate]')) applyTextLanguage(node, language)
    node = walker.nextNode()
  }
  if (root instanceof Element) {
    for (const attribute of translatedAttributes) applyAttributeLanguage(root, attribute, language)
    root.querySelectorAll('*').forEach((element) => {
      if (element.closest('script,style,svg,[data-no-translate]')) return
      for (const attribute of translatedAttributes) applyAttributeLanguage(element, attribute, language)
    })
  }
}

export function useDocumentLanguage(language) {
  useEffect(() => {
    const isUrdu = language === 'ur'
    document.documentElement.lang = isUrdu ? 'ur' : 'en'
    document.documentElement.dir = isUrdu ? 'rtl' : 'ltr'
    translateTree(document.body, language)

    const observer = new MutationObserver((mutations) => {
      for (const mutation of mutations) {
        if (mutation.type === 'characterData') {
          applyTextLanguage(mutation.target, language)
        } else {
          mutation.addedNodes.forEach((node) => {
            if (node.nodeType === Node.TEXT_NODE) applyTextLanguage(node, language)
            else if (node.nodeType === Node.ELEMENT_NODE) translateTree(node, language)
          })
          if (mutation.type === 'attributes' && translatedAttributes.includes(mutation.attributeName)) {
            applyAttributeLanguage(mutation.target, mutation.attributeName, language)
          }
        }
      }
    })
    observer.observe(document.body, { subtree: true, childList: true, characterData: true, attributes: true, attributeFilter: translatedAttributes })
    return () => observer.disconnect()
  }, [language])
}